# Sort lists with .sort()
positions = [20, 50, 4, 19, 15, 1]
print(positions)
positions.sort()
print(positions)

# Sorting a list works for text aswell
text = ["test", "2test2", "FH"]
print(text)
text.sort()
print(text)

# Sorting in reverse
text = ["test", "2test2", "FH"]
print(text)
text.sort(reverse=True)
print(text)