# Range is a function that produces a sequences of numbers
count = range(5)
print(range(3, 7)) # range(3, 7)
print(len(count))

# Range
for num in range(5):
    print(num)

# Range with start and stop
for num in range(3, 7):
    print(num)

# Range with start, stop and step
for num in range(5, 15, 3):
    print(num)